"""Generate 68HC16_PSHM_PULM.sinc: the PSHM/PULM register-list sub-constructors.

PSHM pushes the registers in mask-bit order D, E, IX, IY, IZ, K, CCR, so D is stacked first, at
the highest address. PULM pulls in its own mask-bit order CCR, K, IZ, IY, IX, E, D, from the lowest
address first (CPU16RM PSHM p. 6-173, PULM p. 6-177: "PULM mask order is the reverse of PSHM mask
order"). Masks with the reserved bit 7 set get ",RSVD7" in their text so that Ghidra's assembler
never picks them for a plain register list. The K word packs the four 4-bit extension fields;
each is masked to 4 bits when pushed, so a PULM K restores exactly what PSHM K saved.

usage: python 68HC16_PSHM_PULM.sinc.py [path]            write the .sinc (default: next to this file)
       python 68HC16_PSHM_PULM.sinc.py [path] --check    compare the file with what would be written
"""
import os
import sys

PSHM = ["D", "E", "IX", "IY", "IZ", "K", "CCR"]          # mask bit 0..6
PULM = ["CCR", "K", "IZ", "IY", "IX", "E", "D"]          # mask bit 0..6
PUSH = {"CCR": "local ccr_out:2; syncPushCCR(ccr_out); push16(ccr_out);",
        "K": "local pk:2=(zext(EK:1&0xF)<<12)|(zext(XK:1&0xF)<<8)|(zext(YK:1&0xF)<<4)|zext(ZK:1&0xF); push16(pk);"}
PULL = {"CCR": "pull16(CCR); syncPullPK(CCR);",
        "K": "local un:2; pull16(un); EK=un[12,4]; XK=un[8,4]; YK=un[4,4]; ZK=un[0,4];"}


def push(r):
    return PUSH.get(r, f"push16({r});")


def pull(r):
    return PULL.get(r, f"pull16({r});")


def generate():
    out = ["# 68HC16 PSHM/PULM Register Mapping (generated by 68HC16_PSHM_PULM.sinc.py)", ""]
    out.append("# --- PSHM: pushes in mask-bit order D, E, IX, IY, IZ, K, CCR (D at the highest address) ---")
    for i in range(256):
        regs = [PSHM[b] for b in range(7) if i >> b & 1]
        text = regs + (["RSVD7"] if i & 0x80 else [])
        out.append(f'pshmList: "{",".join(text)}" is regmask=0x{i:02X} {{ {" ".join(push(r) for r in regs)} }}')
    out.append("")
    out.append("# --- PULM: pulls in mask-bit order CCR, K, IZ, IY, IX, E, D (lowest address first) ---")
    for i in range(256):
        regs = [PULM[b] for b in range(7) if i >> b & 1]
        text = regs + (["RSVD7"] if i & 0x80 else [])
        out.append(f'pulmList: "{",".join(text)}" is regmask=0x{i:02X} {{ {" ".join(pull(r) for r in regs)} }}')
    return "\n".join(out) + "\n"


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    path = args[0] if args else os.path.join(os.path.dirname(os.path.abspath(__file__)), "68HC16_PSHM_PULM.sinc")
    text = generate()
    if "--check" in sys.argv:
        with open(path, encoding="utf-8", newline="") as f:
            cur = f.read().replace("\r\n", "\n")
        if cur == text:
            print(f"{path}: up to date")
        else:
            a, b = cur.splitlines(), text.splitlines()
            diff = [n for n, (x, y) in enumerate(zip(a, b)) if x != y]
            sys.exit(f"{path}: differs ({len(a)} vs {len(b)} lines, {len(diff)} lines differ)")
        return
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"Generated {path}")


if __name__ == "__main__":
    main()
